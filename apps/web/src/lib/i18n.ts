const tables = {
  en: en as Record<TranslationKey, string>,
  ar,
} satisfies Record<Locale, Record<TranslationKey, string>>;

export function translate(locale: Locale, key: TranslationKey, params?: Record<string, string | number>) {
  const table = tables[locale] ?? tables.en;
  let value = table[key] ?? tables.en[key] ?? key;

  if (!params) {
    return value;
  }

  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }

  return value;
}
